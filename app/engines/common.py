def hour_to_branch(hour: int) -> int:
    """把 0-23 的钟点换成时辰地支序号。23 点和 0 点都是子时(0)。"""
    return ((hour + 1) // 2) % 12


def sixty_index(stem: int, branch: int) -> int:
    """干支在六十甲子中的序号：满足 idx%10==stem 且 idx%12==branch。"""
    return (6 * stem - 5 * branch) % 60


